std::vector<uint8_t> BitmapFont::renderText(
        const std::string &text,
        int padding, int &outW, int &outH,
        int scale) {
    int charW = 8 * scale, charH = 8 * scale;
    int len = (int)text.size();
    int bmpW = len * charW + padding * 2;
    int bmpH = charH + padding * 2;
    outW = bmpW;
    outH = bmpH;

    std::vector<uint8_t> pixels(bmpW * bmpH * 4, 0);

    for (int i = 0; i < len; i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch < 32 || ch > 126) ch = ' ';
        int idx = ch - 32;
        int baseX = padding + i * charW;

        for (int row = 0; row < 8; row++) {
            uint8_t bits = font8x8[idx][row];
            for (int sy = 0; sy < scale; sy++) {
                int py = padding + row * scale + sy;
                if (py >= bmpH) break;
                for (int col = 0; col < 8; col++) {
                    if (bits & (0x80 >> col)) {
                        for (int sx = 0; sx < scale; sx++) {
                            int px = baseX + col * scale + sx;
                            if (px >= bmpW) break;
                            int pi = (py * bmpW + px) * 4;
                            pixels[pi + 0] = 255;
                            pixels[pi + 1] = 255;
                            pixels[pi + 2] = 255;
                            pixels[pi + 3] = 255;
                        }
                    }
                }
            }
        }
    }
    return pixels;
}
